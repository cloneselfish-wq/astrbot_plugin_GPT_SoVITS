"""识别「群友点名要语音」的请求

默认转语音是一条低概率抽签（``auto.tts_prob``），平时偶尔来一句；
但群友直接说「说句话」「用语音说」「念一下」时，如果还靠抽签，
就会出现「明明点名了却不吭声」的观感问题。

指望模型主动调用 ``gsv_tts`` 工具兜住也不可靠——实测在群聊的真实上下文里
（聊天记录 + 「请直接输出你的回复」），模型会把「XX说句话」读成聊天内容，
直接回文字，两个常用模型都是如此（见 ``_tools/probe_gsv_toolcall.py``）。

所以这里补一条**确定性通道**：命中明确的语音要求就绕过概率，直接转语音。

原则：

- **只在短消息里识别**：长文里出现「语音」多半是在聊别的事情；
- **否定式优先**：「别用语音」「文字就好」不算要求；
- **要明确**：必须出现语音类词（语音 / 声音 / 念 / 唱 / 说给我听），
  或者「说句话」这种只表达「出个声」的口语说法——后者恰恰是最常被用的说法。
"""

from __future__ import annotations

import re

#: 超过这个长度就不做识别——长文里的「语音」基本不是在要求换形式
MAX_SCAN_LEN = 30

# 明确要求：命中任意一条即视为「点名要语音」
_PATTERNS: tuple[tuple[str, str], ...] = (
    # 直接点名「语音」
    (r"语音", r"(?:发|来|用|说|录|整|出|给)(?:一?条|一?段|一?句|一?个|个)?\s*语音"),
    (r"语音", r"语音(?:说|讲|回复|回答|念|读|来)"),
    (r"语音", r"语音(?:条|消息|模式)"),
    # 「用你的声音」「听你的声音」
    (r"声音", r"(?:用|以|拿)(?:你|妳|妳的|你的)?(?:的)?(?:声音|声线)"),
    (r"声音", r"(?:想|要|来)?听(?:一下)?(?:你|妳)(?:的)?(?:声音|声线)"),
    (r"出声", r"出(?:个)?声"),
    (r"开嗓", r"开嗓"),
    # 「说句话」「说一句」「说两句」「说几句」「说个话」「说段话」「说点什么」
    (r"说句话", r"说(?:一|两|二|三|几|两?三)?(?:句|段|个|点)(?:话|话儿|话吧|话呗)?"),
    # 「念一下」「念给我听」
    (r"念一下", r"(?:念|读)(?:一?下|一?遍|一?段)"),
    (r"念给我听", r"(?:念|读|说|唱)(?:给|来)(?:我|吾|咱)"),
    # 「说给我听」「听你说」
    (r"说给我听", r"说(?:给|来)(?:我|吾|咱)(?:听)?"),
    (r"听你说", r"听(?:你|妳)(?:说|讲|唱)"),
    # 「唱一句」
    (r"唱一句", r"唱(?:一|两|二|几)?(?:句|段|首|个)"),
    (r"唱歌", r"唱(?:首|个|支)歌"),
    # 英文 / 日文
    (r"voice", r"(?:send|leave|record)?\s*(?:a\s+)?voice\s*(?:message|msg|note)"),
    (r"out loud", r"say\s+it\s+(?:out\s+loud|with\s+your\s+voice)"),
    (r"声で", r"声(?:で|を)(?:言|話|聞かせ)"),
)

# 否定式：命中即否决（「别说语音」「文字就好」）
_NEGATIVE_PATTERNS: tuple[str, ...] = (
    r"(?:别|不要|不用|不准|不许|甭|莫|不必|别再|不用再|先别)\s*"
    r"(?:再|给我|老|又)?\s*(?:发|用|说|唱|念|来|整|录|出)?\s*"
    r"(?:语音|声音|声|话)",
    r"(?:文字|打字|发字)(?:就|即)?(?:好|行|可以|吧|得了)",
    r"(?:别|不要|不用)\s*(?:出声|说话|开嗓)",
    r"(?:不用|不必|别)\s*(?:念|读|唱)",
)

_POSITIVE: list[tuple[str, re.Pattern[str]]] = [
    (name, re.compile(pattern)) for name, pattern in _PATTERNS
]
_NEGATIVE: list[re.Pattern[str]] = [re.compile(p) for p in _NEGATIVE_PATTERNS]


def parse_voice_request(text: str) -> str:
    """从用户消息里识别「点名要语音」

    :param text: 用户发来的消息
    :return: 命中的关键词（用于日志）；没命中返回空串
    """

    if not text:
        return ""

    content = text.strip()
    if not content or len(content) > MAX_SCAN_LEN:
        return ""

    # 否定式优先：「别用语音」里含有「用语音」，必须先拦掉
    for pattern in _NEGATIVE:
        if pattern.search(content):
            return ""

    for name, pattern in _POSITIVE:
        if pattern.search(content):
            return name

    return ""
